package enrollserver

import (
	"io"
	"net/http"
	"regexp"
	"strings"
)

// handleCA serves the public CA bundle — the trust anchor. It carries no
// secrets (it is the same bundle enrollment returns); its authenticity
// comes from pinning its fingerprint out-of-band.
func (s *Server) handleCA(w http.ResponseWriter, r *http.Request) {
	if s.CA == nil {
		httpError(w, http.StatusNotFound, "CA not initialized")
		return
	}
	w.Header().Set("Content-Type", "application/x-pem-file")
	w.Write(s.CA.CertPEM())
}

// fingerprintHex matches a 64-char lowercase hex SHA-256 digest.
var fingerprintHex = regexp.MustCompile(`^[0-9a-f]{64}$`)

// handleEnrollScript serves the one-shot bootstrap script:
//
//	curl -fsSLk -d "<CA_FINGERPRINT>" https://control:8443/enroll.sh | sudo sh -s -- \
//	    --token TOKEN --hostname web01
//
// POST body (or GET ?pin=) is the expected CA fingerprint; the script
// then downloads the right agent binary over the pinned channel,
// verifies its served digest, enrolls this host, brings up WireGuard and
// installs a systemd unit for persistence. The enrollment token is the
// access credential and is deliberately NOT embedded in a served script:
// it is passed at run time (whoever holds the token decides which host
// name it is burned on).
func (s *Server) handleEnrollScript(w http.ResponseWriter, r *http.Request) {
	pin := r.URL.Query().Get("pin")
	if r.Method == http.MethodPost {
		body, err := io.ReadAll(io.LimitReader(r.Body, 4096))
		if err != nil {
			httpError(w, http.StatusBadRequest, "read pin: "+err.Error())
			return
		}
		pin = strings.TrimSpace(string(body))
		// Accept a raw digest (curl -d "$PIN") or a pin= form field.
		if v, ok := strings.CutPrefix(pin, "pin="); ok {
			pin = strings.TrimSpace(v)
		}
	}
	pin = strings.ToLower(pin)
	if pin != "" && !fingerprintHex.MatchString(pin) {
		httpError(w, http.StatusBadRequest,
			"pin must be the 64-char hex SHA-256 of the CA certificate")
		return
	}

	w.Header().Set("Content-Type", "text/x-shellscript; charset=utf-8")
	io.WriteString(w, enrollScript(requestBaseURL(r), pin))
}

// requestBaseURL derives the https://host:port the script was fetched
// from, so the script needs no --server argument in the common case.
func requestBaseURL(r *http.Request) string {
	scheme := "https"
	if v := r.Header.Get("X-Forwarded-Proto"); v != "" {
		scheme = v
	}
	return scheme + "://" + r.Host
}

// enrollScript renders the bootstrap script for a server URL and an
// optional pinned CA fingerprint (empty = the operator passes --pin).
func enrollScript(serverURL, pin string) string {
	return strings.NewReplacer(
		"__SERVER__", serverURL,
		"__PIN__", pin,
	).Replace(enrollScriptTemplate)
}

// enrollScriptTemplate is POSIX sh on purpose: it runs on any Linux
// (and on macOS for testing with --no-systemd). Placeholders are
// __SERVER__ and __PIN__.
const enrollScriptTemplate = `#!/bin/sh
# claymod bootstrap — generated by claymod serve. Enrolls this host:
# downloads the agent binary, verifies it against the pinned CA and its
# served SHA-256, enrolls, brings up WireGuard and installs a systemd
# unit so the agent survives reboots.
#
#   curl -fsSLk -d "<CA_FINGERPRINT>" __SERVER__/enroll.sh | sudo sh -s -- \
#       --token TOKEN --hostname web01
# (the -k is required: the bootstrap certificate comes from claymod's
#  internal CA. The fingerprint you pass IS the trust anchor.)
#
# Requires root and the enrollment token (ask your operator). The token
# is the access credential; the fingerprint authenticates everything
# downloaded below.
set -eu

SERVER="__SERVER__"
PIN="__PIN__"
TOKEN=""
HOSTNAME=""
OUT_DIR="/etc/claymod"
BIN_DIR="/usr/local/bin"
SKIP_WG=0
NO_SYSTEMD=0

while [ "$#" -gt 0 ]; do
  case "$1" in
    --token)     TOKEN="$2"; shift 2 ;;
    --hostname)  HOSTNAME="$2"; shift 2 ;;
    --pin)       PIN="$2"; shift 2 ;;
    --server)    SERVER="$2"; shift 2 ;;
    --out-dir)   OUT_DIR="$2"; shift 2 ;;
    --bin-dir)   BIN_DIR="$2"; shift 2 ;;
    --skip-wg)   SKIP_WG=1; shift ;;
    --no-systemd) NO_SYSTEMD=1; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done

[ -n "$TOKEN" ]    || { echo "missing --token (one-time enrollment token)" >&2; exit 2; }
[ -n "$HOSTNAME" ] || { echo "missing --hostname" >&2; exit 2; }
[ -n "$PIN" ]      || { echo "missing --pin (CA fingerprint, 64 hex chars)" >&2; exit 2; }
[ "$(id -u)" = "0" ] || { echo "run as root: curl ... | sudo sh -s -- ..." >&2; exit 2; }

echo "== claymod bootstrap: $HOSTNAME -> $SERVER"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

sha256() {
  if command -v sha256sum >/dev/null 2>&1; then
    sha256sum "$1" | awk '{print $1}'
  else
    shasum -a 256 "$1" | awk '{print $1}'
  fi
}

# 1. Fetch the CA bundle and verify it against the pinned fingerprint.
#    The transport of this fetch is untrusted on purpose: the pinned
#    fingerprint IS the trust (same model as a pinned download).
curl -fsS -k -o "$WORK/ca.pem" "$SERVER/ca.pem"
ACTUAL="$(openssl x509 -in "$WORK/ca.pem" -outform DER -out "$WORK/ca.der"
sha256 "$WORK/ca.der")"
if [ "$ACTUAL" != "$PIN" ]; then
  echo "SECURITY FAILURE: CA fingerprint mismatch (got $ACTUAL, want $PIN)" >&2
  exit 1
fi
echo "== CA verified: $ACTUAL"
# Trust exactly the verified certificate: never the raw bundle (appended
# certificates must not become trust roots).
openssl x509 -in "$WORK/ca.pem" -out "$WORK/ca.pem.pinned"
mv "$WORK/ca.pem.pinned" "$WORK/ca.pem"

# 2. Pick the agent binary for this platform.
OS="$(uname -s | tr '[:upper:]' '[:lower:]')"
ARCH="$(uname -m)"
case "$ARCH" in
  x86_64)        ARCH=amd64 ;;
  aarch64|arm64) ARCH=arm64 ;;
esac

# 3. Download the agent over the verified channel and check its digest.
curl -fsS --cacert "$WORK/ca.pem" -o "$WORK/claymod-agent" \
  "$SERVER/agent/$OS/$ARCH"
curl -fsS --cacert "$WORK/ca.pem" -o "$WORK/agent.sha256" \
  "$SERVER/agent/$OS/$ARCH.sha256"
AGENT_SHA="$(sha256 "$WORK/claymod-agent")"
WANT_SHA="$(awk '{print $1}' "$WORK/agent.sha256")"
if [ "$AGENT_SHA" != "$WANT_SHA" ]; then
  echo "SECURITY FAILURE: agent digest mismatch ($AGENT_SHA != $WANT_SHA)" >&2
  exit 1
fi
echo "== agent verified: $AGENT_SHA"
chmod 0755 "$WORK/claymod-agent"

# 4. Enroll: the WireGuard key pair is generated here and never leaves
#    this host.
"$WORK/claymod-agent" enroll \
  --server "$SERVER" \
  --token "$TOKEN" \
  --hostname "$HOSTNAME" \
  --ca "$WORK/ca.pem" \
  --out-dir "$OUT_DIR" \
  --skip-wg-config

# 5. WireGuard interface (the one root-only step of enrollment).
if [ "$SKIP_WG" = "0" ]; then
  "$WORK/claymod-agent" wg-setup --out-dir "$OUT_DIR"
else
  echo "== WireGuard bring-up skipped (--skip-wg)"
fi

# 6. Install the agent and a systemd unit so it survives reboots.
mkdir -p "$BIN_DIR"
cp "$WORK/claymod-agent" "$BIN_DIR/claymod-agent"
if [ "$NO_SYSTEMD" = "0" ]; then
  cat > /etc/systemd/system/claymod-agent.service <<UNIT
[Unit]
Description=claymod host agent
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=$BIN_DIR/claymod-agent agent --config $OUT_DIR/agent.yaml
Restart=always
RestartSec=5s

[Install]
WantedBy=multi-user.target
UNIT
  systemctl daemon-reload
  systemctl enable --now claymod-agent.service
  echo "== systemd unit claymod-agent.service installed and started"
else
  echo "== systemd skipped (--no-systemd); agent installed at $BIN_DIR/claymod-agent"
fi

echo "== bootstrap complete: $HOSTNAME is enrolled"
if [ "$NO_SYSTEMD" = "1" ]; then
  echo "   start it with: $BIN_DIR/claymod-agent agent --config $OUT_DIR/agent.yaml"
fi
`
