package wgmgr

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// execCommand runs a system command, returning its combined output.
func execCommand(name string, args ...string) ([]byte, error) {
	return exec.Command(name, args...).CombinedOutput()
}

// ConfConfig describes the WireGuard interface to render.
type ConfConfig struct {
	// Interface is the device name (e.g. "claymod0").
	Interface string
	// Overlay is the interface address in CIDR form (e.g. "10.42.0.1/24").
	Overlay string
	// ListenPort is the UDP listen port.
	ListenPort int
	// PrivateKey is the control server's base64 private key.
	PrivateKey string
	// Peers to install (sorted by hostname for stable output).
	//
	// In WireGuard's model the *agent* initiates to the server
	// (persistent-keepalive on the agent side), so the server's conf has
	// no per-peer Endpoint lines: the server only sets its own listen
	// port and each peer's AllowedIPs.
	Peers []Peer
}

// RenderConf renders a wg-quick(8) configuration for the control
// server's WireGuard interface. The private key is embedded: the file
// must be written 0600 (WriteConf enforces this).
func RenderConf(cfg ConfConfig) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# claymod — generated by `claymod serve`; do not edit.\n")
	fmt.Fprintf(&b, "# Regenerated on every enrollment change. Apply with:\n")
	fmt.Fprintf(&b, "#   wg-quick up %[1]s   (first time)\n", cfg.Interface)
	fmt.Fprintf(&b, "#   wg syncconf %[1]s <(wg-quick strip %[1]s)   (updates)\n", cfg.Interface)
	fmt.Fprintf(&b, "[Interface]\n")
	fmt.Fprintf(&b, "Address = %s\n", cfg.Overlay)
	fmt.Fprintf(&b, "ListenPort = %d\n", cfg.ListenPort)
	fmt.Fprintf(&b, "PrivateKey = %s\n", cfg.PrivateKey)
	peers := append([]Peer(nil), cfg.Peers...)
	sort.Slice(peers, func(i, j int) bool { return peers[i].Hostname < peers[j].Hostname })
	for _, p := range peers {
		fmt.Fprintf(&b, "\n# %s\n", p.Hostname)
		fmt.Fprintf(&b, "[Peer]\n")
		fmt.Fprintf(&b, "PublicKey = %s\n", p.PublicKey)
		fmt.Fprintf(&b, "AllowedIPs = %s\n", p.AllowedIPs)
		if p.Endpoint != "" {
			fmt.Fprintf(&b, "Endpoint = %s\n", p.Endpoint)
		}
		if p.PersistentKeepalive > 0 {
			fmt.Fprintf(&b, "PersistentKeepalive = %d\n", p.PersistentKeepalive)
		}
	}
	return b.String()
}

// EnsureAgentInterface brings up a HOST-side WireGuard interface with a
// single peer (the control server) using the system's `ip` and `wg`
// commands. Like EnsureInterface it requires CAP_NET_ADMIN and
// deliberately shells out instead of linking netlink.
func EnsureAgentInterface(cfg ConfConfig, server Peer) error {
	runner := sysRunner
	if err := runner("ip", "link", "add", "dev", cfg.Interface, "type", "wireguard"); err != nil {
		if !strings.Contains(err.Error(), "exists") &&
			!strings.Contains(err.Error(), "File exists") {
			return fmt.Errorf("wgmgr: create interface %s: %w", cfg.Interface, err)
		}
	}
	if err := runner("ip", "-4", "address", "replace",
		cfg.Overlay, "dev", cfg.Interface); err != nil {
		return fmt.Errorf("wgmgr: set address: %w", err)
	}
	keyFile, err := writeTempKey(cfg.PrivateKey)
	if err != nil {
		return err
	}
	defer os.Remove(keyFile)
	if err := runner("wg", "set", cfg.Interface,
		"private-key", keyFile,
		"listen-port", fmt.Sprintf("%d", cfg.ListenPort)); err != nil {
		return fmt.Errorf("wgmgr: wg set: %w", err)
	}
	// The control-server peer: agents initiate and keep the mapping warm.
	args := []string{"set", cfg.Interface,
		"peer", server.PublicKey,
		"allowed-ips", server.AllowedIPs,
	}
	if server.Endpoint != "" {
		args = append(args, "endpoint", server.Endpoint)
	}
	if server.PersistentKeepalive > 0 {
		args = append(args, "persistent-keepalive",
			fmt.Sprintf("%d", server.PersistentKeepalive))
	}
	if err := runner("wg", args...); err != nil {
		return fmt.Errorf("wgmgr: add server peer: %w", err)
	}
	if err := runner("ip", "link", "set", "up", "dev", cfg.Interface); err != nil {
		return fmt.Errorf("wgmgr: link up: %w", err)
	}
	return nil
}

// WriteConf renders and persists the interface configuration at path
// with 0600 permissions (it contains the private key).
func WriteConf(path string, cfg ConfConfig) error {
	if cfg.PrivateKey == "" {
		return fmt.Errorf("wgmgr: refuse to write a config without a private key")
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(RenderConf(cfg)), 0o600); err != nil {
		return fmt.Errorf("wgmgr: write conf: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		return fmt.Errorf("wgmgr: replace conf: %w", err)
	}
	return nil
}

// ConfPath returns the conventional configuration path inside the
// server data directory.
func ConfPath(dataDir, iface string) string {
	return filepath.Join(dataDir, iface+".conf")
}

// EnsureInterface brings the WireGuard interface up to the given
// configuration using the system's `ip` and `wg` commands: create the
// interface if missing, set the address, private key and listen port.
// Peers are managed separately through the Backend (wgctrl).
//
// Requires CAP_NET_ADMIN (typically root). This deliberately shells out
// to `ip`/`wg` instead of pulling in a netlink dependency: the commands
// are stable, auditable and present everywhere WireGuard is.
func EnsureInterface(cfg ConfConfig) error {
	runner := sysRunner
	if err := runner("ip", "link", "add", "dev", cfg.Interface, "type", "wireguard"); err != nil {
		// "exists" is fine on restart; anything else is fatal.
		if !strings.Contains(err.Error(), "exists") &&
			!strings.Contains(err.Error(), "File exists") {
			return fmt.Errorf("wgmgr: create interface %s: %w", cfg.Interface, err)
		}
	}
	if err := runner("ip", "-4", "address", "replace",
		cfg.Overlay, "dev", cfg.Interface); err != nil {
		return fmt.Errorf("wgmgr: set address: %w", err)
	}
	keyFile, err := writeTempKey(cfg.PrivateKey)
	if err != nil {
		return err
	}
	defer os.Remove(keyFile)
	if err := runner("wg", "set", cfg.Interface,
		"private-key", keyFile,
		"listen-port", fmt.Sprintf("%d", cfg.ListenPort)); err != nil {
		return fmt.Errorf("wgmgr: wg set: %w", err)
	}
	if err := runner("ip", "link", "set", "up", "dev", cfg.Interface); err != nil {
		return fmt.Errorf("wgmgr: link up: %w", err)
	}
	return nil
}

// writeTempKey writes the private key to a 0600 temp file for `wg set`
// (the wg CLI reads keys from a file, never argv).
func writeTempKey(privateKey string) (string, error) {
	f, err := os.CreateTemp("", "claymod-wgkey-*")
	if err != nil {
		return "", fmt.Errorf("wgmgr: temp key file: %w", err)
	}
	if err := f.Chmod(0o600); err != nil {
		f.Close()
		os.Remove(f.Name())
		return "", fmt.Errorf("wgmgr: temp key perms: %w", err)
	}
	if _, err := f.WriteString(privateKey + "\n"); err != nil {
		f.Close()
		os.Remove(f.Name())
		return "", fmt.Errorf("wgmgr: write key: %w", err)
	}
	if err := f.Close(); err != nil {
		os.Remove(f.Name())
		return "", fmt.Errorf("wgmgr: close key: %w", err)
	}
	return f.Name(), nil
}

// sysRunner executes a system command and returns its combined output as
// an error message when it fails. Overridable in tests.
var sysRunner = func(name string, args ...string) error {
	out, err := execCommand(name, args...)
	if err != nil {
		msg := strings.TrimSpace(string(out))
		if msg == "" {
			msg = err.Error()
		}
		return fmt.Errorf("%s: %s", name, msg)
	}
	return nil
}
