func TestRenderConfGolden(t *testing.T) {
	conf := RenderConf(ConfConfig{
		Interface:  "claymod0",
		Overlay:    "10.42.0.1/24",
		ListenPort: 51821,
		PrivateKey: "SERVERPRIV",
		Peers: []Peer{
			{Hostname: "web02", PublicKey: "PK2", AllowedIPs: "10.42.0.3/32"},
			{Hostname: "web01", PublicKey: "PK1", AllowedIPs: "10.42.0.2/32"},
		},
	})
	want := `# claymod — generated by ` + "`claymod serve`" + `; do not edit.
# Regenerated on every enrollment change. Apply with:
#   wg-quick up claymod0   (first time)
#   wg syncconf claymod0 <(wg-quick strip claymod0)   (updates)
[Interface]
Address = 10.42.0.1/24
ListenPort = 51821
PrivateKey = SERVERPRIV

# web01
[Peer]
PublicKey = PK1
AllowedIPs = 10.42.0.2/32

# web02
[Peer]
PublicKey = PK2
AllowedIPs = 10.42.0.3/32
`
	if conf != want {
		t.Errorf("conf mismatch:\n got:\n%s\nwant:\n%s", conf, want)
	}
}

func TestWriteConfPersistsAt0600(t *testing.T) {
	path := filepath.Join(t.TempDir(), "claymod0.conf")
	cfg := ConfConfig{
		Interface:  "claymod0",
		Overlay:    "10.42.0.1/24",
		ListenPort: 51821,
		PrivateKey: "SECRET",
	}
	if err := WriteConf(path, cfg); err != nil {
		t.Fatalf("WriteConf returned error: %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(data), "PrivateKey = SECRET") {
		t.Error("conf missing the private key")
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	if perm := info.Mode().Perm(); perm != 0o600 {
		t.Errorf("conf mode = %o, want 600 (contains a private key)", perm)
	}
}

func TestWriteConfRefusesEmptyKey(t *testing.T) {
	path := filepath.Join(t.TempDir(), "claymod0.conf")
	err := WriteConf(path, ConfConfig{Interface: "claymod0"})
	if err == nil {
		t.Fatal("WriteConf accepted an empty private key")
	}
	if _, statErr := os.Stat(path); !os.IsNotExist(statErr) {
		t.Error("WriteConf created a file despite refusing")
	}
}

func TestManagerPersistsConfOnEnrollRevoke(t *testing.T) {
	path := filepath.Join(t.TempDir(), "claymod0.conf")
	backend := NewFakeBackend()
	m := NewWithKeys("claymod0", KeyPair{Private: "PRIV", Public: "PUB"},
		backend, "127.0.0.1:51821")
	m.Overlay = "10.42.0.1/24"
	m.ListenPort = 51821
	m.ConfPath = path

	if err := m.Enroll("web01", "PK1", "10.42.0.2"); err != nil {
		t.Fatalf("Enroll returned error: %v", err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("conf not written on enroll: %v", err)
	}
	if !strings.Contains(string(data), "# web01") || !strings.Contains(string(data), "10.42.0.2/32") {
		t.Errorf("conf missing web01 peer:\n%s", data)
	}

	if err := m.Revoke("PK1"); err != nil {
		t.Fatalf("Revoke returned error: %v", err)
	}
	data, err = os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(data), "# web01") {
		t.Errorf("conf still lists revoked web01:\n%s", data)
	}
}

func TestResyncInstallsInventoryPeers(t *testing.T) {
	path := filepath.Join(t.TempDir(), "claymod0.conf")
	m := NewWithKeys("claymod0", KeyPair{Private: "PRIV"}, NewFakeBackend(), "")
	m.Overlay = "10.42.0.1/24"
	m.ListenPort = 51821
	m.ConfPath = path

	// Simulate a restart: inventory hands back two hosts.
	if err := m.Resync([]Peer{
		{Hostname: "web01", PublicKey: "PK1", AllowedIPs: "10.42.0.2/32"},
		{Hostname: "web02", PublicKey: "PK2", AllowedIPs: "10.42.0.3/32"},
	}); err != nil {
		t.Fatalf("Resync returned error: %v", err)
	}
	peers, err := m.Peers()
	if err != nil {
		t.Fatal(err)
	}
	if len(peers) != 2 {
		t.Fatalf("Peers after resync = %d, want 2", len(peers))
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"# web01", "# web02", "10.42.0.2/32", "10.42.0.3/32"} {
		if !strings.Contains(string(data), want) {
			t.Errorf("conf missing %q after resync", want)
		}
	}
}

// TestEnsureInterfaceUsesSystemCommands verifies the command sequence
// (create link, set address, wg set with a key file, link up) against a
// recorded runner — no root required.
func TestEnsureInterfaceUsesSystemCommands(t *testing.T) {
	var calls [][]string
	old := sysRunner
	sysRunner = func(name string, args ...string) error {
		calls = append(calls, append([]string{name}, args...))
		if name == "ip" && len(args) >= 3 && args[0] == "link" && args[1] == "add" {
			return errExists // second run: interface already exists
		}
		return nil
	}
	defer func() { sysRunner = old }()

	err := EnsureInterface(ConfConfig{
		Interface:  "claymod0",
		Overlay:    "10.42.0.1/24",
		ListenPort: 51821,
		PrivateKey: "PRIVKEY",
	})
	if err != nil {
		t.Fatalf("EnsureInterface returned error: %v", err)
	}

	wantSeq := []string{
		"ip link add dev claymod0 type wireguard",
		"ip -4 address replace 10.42.0.1/24 dev claymod0",
		"wg set claymod0 private-key <tmpfile> listen-port 51821",
		"ip link set up dev claymod0",
	}
	if len(calls) != len(wantSeq) {
		t.Fatalf("ran %d commands, want %d: %v", len(calls), len(wantSeq), calls)
	}
	for k, want := range wantSeq {
		got := strings.Join(calls[k], " ")
		if want == "wg set claymod0 private-key <tmpfile> listen-port 51821" {
			// The key file path is a temp file: match the shape.
			if !strings.HasPrefix(got, "wg set claymod0 private-key ") ||
				!strings.HasSuffix(got, " listen-port 51821") {
				t.Errorf("call %d = %q, want a wg set with temp key file", k, got)
			}
			continue
		}
		if got != want {
			t.Errorf("call %d = %q, want %q", k, got, want)
		}
	}
}

// TestEnsureInterfaceSurfacesFailures: a failing `ip` (other than
// "exists") aborts with the command's message.
func TestEnsureInterfaceSurfacesFailures(t *testing.T) {
	old := sysRunner
	sysRunner = func(name string, args ...string) error {
		// `ip -4 address replace …` — the flag is args[0].
		if name == "ip" && len(args) > 0 && args[0] == "-4" {
			return errAddr
		}
		return nil
	}
	defer func() { sysRunner = old }()

	err := EnsureInterface(ConfConfig{
		Interface: "claymod0", Overlay: "10.42.0.1/24", ListenPort: 51821, PrivateKey: "K",
	})
	if err == nil {
		t.Fatal("EnsureInterface ignored a failing address command")
	}
	if !strings.Contains(err.Error(), "set address") {
		t.Errorf("error = %q, want set-address context", err.Error())
	}
}

// TestEnsureAgentInterfaceUsesSystemCommands: the host-side bring-up
// sequence (link, address, wg set key, wg set server peer, up).
func TestEnsureAgentInterfaceUsesSystemCommands(t *testing.T) {
	var calls [][]string
	old := sysRunner
	sysRunner = func(name string, args ...string) error {
		calls = append(calls, append([]string{name}, args...))
		return nil
	}
	defer func() { sysRunner = old }()

	err := EnsureAgentInterface(ConfConfig{
		Interface:  "claymod0",
		Overlay:    "10.42.0.2/24",
		ListenPort: 51821,
		PrivateKey: "HOSTPRIV",
	}, Peer{
		PublicKey:           "SERVERPUB",
		AllowedIPs:          "10.42.0.0/24",
		Endpoint:            "vps.example:51821",
		PersistentKeepalive: 25,
	})
	if err != nil {
		t.Fatalf("EnsureAgentInterface returned error: %v", err)
	}
	var joined []string
	for _, c := range calls {
		joined = append(joined, strings.Join(c, " "))
	}
	whole := strings.Join(joined, " | ")
	for _, want := range []string{
		"ip link add dev claymod0 type wireguard",
		"ip -4 address replace 10.42.0.2/24 dev claymod0",
		"wg set claymod0 private-key ",
		"wg set claymod0 peer SERVERPUB allowed-ips 10.42.0.0/24 endpoint vps.example:51821 persistent-keepalive 25",
		"ip link set up dev claymod0",
	} {
		if !strings.Contains(whole, want) {
			t.Errorf("command sequence missing %q:\n%s", want, whole)
		}
	}
}

// TestPeersFuncIsSourceOfTruth: when PeersFunc is set (serve wires it to
// the inventory), the config file reflects it — not the manager's map —
// so serve and `host revoke` converge on the DB state.
func TestPeersFuncIsSourceOfTruth(t *testing.T) {
	path := filepath.Join(t.TempDir(), "claymod0.conf")
	m := NewWithKeys("claymod0", KeyPair{Private: "PRIV"}, NewFakeBackend(), "")
	m.Overlay = "10.42.0.1/24"
	m.ListenPort = 51821
	m.ConfPath = path

	dbPeers := []Peer{
		{Hostname: "web01", PublicKey: "PK1", AllowedIPs: "10.42.0.2/32"},
	}
	m.PeersFunc = func() ([]Peer, error) { return dbPeers, nil }

	// Enroll adds to the map AND (via PeersFunc) to the conf.
	if err := m.Enroll("web01", "PK1", "10.42.0.2"); err != nil {
		t.Fatal(err)
	}
	// Simulate `host revoke` removing web01 from the DB behind serve's
	// back: the next refresh must drop it from the file.
	dbPeers = nil
	if err := m.RefreshConf(); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(data), "# web01") {
		t.Errorf("conf resurrected a DB-removed peer:\n%s", data)
	}
}

